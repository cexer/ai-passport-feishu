"""Generate the public console QR as read-only RGB565 (qrcode is build-time only)."""
from pathlib import Path
import hashlib,json
import qrcode

root=Path(__file__).resolve().parents[1]
url='https://xiaozhi.me/console/'
qr=qrcode.QRCode(error_correction=qrcode.constants.ERROR_CORRECT_M,box_size=4,border=4)
qr.add_data(url,optimize=0);qr.make(fit=True);matrix=qr.get_matrix()
scale=4;side=len(matrix)*scale;assert side==148
light=(0xD9,0xE7,0xE2);dark=(0x20,0x3E,0x4B)
def rgb565(c):return ((c[0]>>3)<<11)|((c[1]>>2)<<5)|(c[2]>>3)
pixels=[rgb565(dark if matrix[y//scale][x//scale] else light) for y in range(side) for x in range(side)]
header='''/* Generated by tools/generate_xiao_console_qr.py. Public URL, no credentials.
 * RGB565 pixels stay in Flash; no indexed decode or QR canvas is required. */
#pragma once
#include "lvgl.h"
#define FEISHU_XIAO_CONSOLE_URL "https://xiaozhi.me/console/"
static const uint16_t feishu_xiao_console_qr_pixels[] = {
'''
header+=''.join('    '+','.join('0x%04x'%v for v in pixels[i:i+16])+',\n' for i in range(0,len(pixels),16))
header+='''};
static const lv_image_dsc_t feishu_xiao_console_qr={
    .header={.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_RGB565,.w=148,.h=148,.stride=296},
    .data_size=sizeof(feishu_xiao_console_qr_pixels),.data=(const uint8_t *)feishu_xiao_console_qr_pixels,
};
'''
out=root/'main/feishu_xiao_console_qr.h';out.write_text(header,encoding='utf-8')
metadata={'url':url,'ecc':'M','quiet_modules':4,'scale':scale,'side':side,'flash_pixel_bytes':len(pixels)*2,'header_sha256':hashlib.sha256(out.read_bytes()).hexdigest()}
(root/'assets/xiao-console-qr.json').write_text(json.dumps(metadata,indent=2)+'\n',encoding='utf-8')
print(json.dumps(metadata))
